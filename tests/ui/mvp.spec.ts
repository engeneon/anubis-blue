import { test, expect } from '@playwright/test';
import { readFileSync, mkdirSync, writeFileSync } from 'node:fs';
const token='ui-test-token-not-a-production-secret';
const output='implementation/mvp-1.0';
test('MVP document assistant calculation handoff closure and retrieval', async ({page,request})=>{
 test.setTimeout(120000); page.setDefaultTimeout(12000); mkdirSync(output,{recursive:true});
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
  const headers = { Authorization: "Bearer " + token };
  const post = async (path: string, data: unknown) => {
    const r = await request.post("/api/v1/" + path, { headers, data });
    expect(r.ok(), await r.text()).toBeTruthy();
    return r.json();
  };
  await page.goto("/");
  await page.getByLabel("Access token").fill(token);
  await page.getByRole("button", { name: "Open workspace" }).click();
  await page.getByRole("button", { name: "Consultant Copilot", exact: true }).click();
  await page.getByLabel("Customer workload name").fill("MVP document assistant");
  const created = page.waitForResponse(r => r.url().endsWith("/copilot-sessions") && r.request().method() === "POST");
  await page.getByRole("button", { name: "Start assisted engagement" }).click();
  const session = await (await created).json();
  const story = "A local answer model serves engineers using passages from an existing search system outside this AI Factory. The busiest hour has 2,400 questions. The external search system indexes a 4 TB document corpus. For this pilot, explicitly assume dense8b, 2,000 input tokens and 500 output tokens per call.";
  const source = await post(`copilot-sessions/${session.id}/sources`, {name:"Case A",kind:"message",text:story});
  const fact = (concept: string, value: string, unit="", period_value="", period_unit="", status="reported") => ({activity:"Document assistant",concept,value,unit,period_value,period_unit,status,source_id:source.id,quote:story});
  await post(`copilot-sessions/${session.id}/proposals`, {facts:[
    fact("text_model","yes"),fact("search","yes"),fact("compute_location","local"),fact("search_location","external"),fact("data_location","external"),fact("storage","4","TB"),fact("requests_peak","2400","request","1","hour"),fact("demand_basis","measured_peak"),fact("model","dense8b","","","","assumed"),fact("input_tokens","2000","token","","","assumed"),fact("output_tokens","500","token","","","assumed")
  ]});
  await page.getByRole("button", {name:"Refresh session",exact:true}).click();
  await page.getByLabel("I reviewed the selected values and accept the planning assumptions.").check();
  await page.getByRole("button", {name:"Apply selected",exact:true}).click();

 await page.getByRole('button',{name:'Review and calculate GPU estimate',exact:true}).click();
 await page.getByLabel('Use these planning assumptions').check();
 await page.getByRole('button',{name:'Calculate estimate',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Your requirements at a glance',exact:true})).toBeVisible();
 await expect(page.getByRole('heading',{name:'GPU workload comparison',exact:true})).toBeVisible();
 const download=async(name:string)=>{const [d]=await Promise.all([page.waitForEvent('download'),page.getByRole('button',{name,exact:true}).click()]);return readFileSync((await d.path())!,'utf8');};
 const result=JSON.parse(await download('Export result'));const p=result.planning;
 expect(p.raw_gpus).toBe(8);expect(p.initial_gpus).toBe(256);
 expect(p.hardware_comparison.map((h:any)=>h.platform).sort()).toEqual(['HGX_B200','HGX_B300','HGX_H200']);
 for(const h of p.hardware_comparison)expect(h.raw_gpus).toBe(8);
 expect(Number(p.stage_calculations[0].demand)).toBeCloseTo(2400/3600,5);
 const kv=2*32*8*128*2*8192*32/1e9;
 expect(Number(p.required_GB_per_gpu)).toBeCloseTo(16+kv+8,5);
 expect(p.storage).toEqual([]);
 expect(p.networks.external_customer_datacenter.initial_load_link_Gbps).toBeNull();
 expect(p.networks.storage.dedicated).toBe(true);expect(p.networks.storage.converged).toBe(false);
 const summary=await download('Download requirements summary');
 expect(summary).toContain('Measurement required');expect(summary).toContain('256 GPUs');
 for(const role of ['North-south traffic','External customer connection','Dedicated storage network','East-west GPU network'])expect(summary).toContain(role);
 await page.screenshot({path:output+'/01-requirements.png',fullPage:true});
 await page.getByRole('button',{name:'Continue to Design handoff',exact:true}).click();
 await page.getByRole('button',{name:'Prepare projection',exact:true}).click();
 await expect(page.getByRole('heading',{name:'AI Factory design executive summary',exact:true})).toBeVisible();
 await page.screenshot({path:output+'/02-handoff.png',fullPage:true});
 await page.getByLabel('Completion notes',{exact:true}).fill('MVP validation. Planning requirements delivered. External corpus remains outside the factory.');
 await page.getByLabel('I confirm that these selected requirements are delivered.',{exact:true}).check();
 await page.getByRole('button',{name:'Complete engagement',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Saved deliverables',exact:true})).toBeVisible();
 await page.reload();await page.getByRole('button',{name:'Cases',exact:true}).click();
 const row=page.locator('.engagement-row').filter({hasText:'MVP document assistant'});
 await expect(row).toContainText('Completed · requirements delivered');
 await row.getByRole('button',{name:'View engagement',exact:true}).click();
 const record=JSON.parse(await download('Download complete engagement record'));
 expect(record.data.result_snapshot.result.planning).toEqual(p);
 expect(record.data.projection_snapshot.companion_requirements).toMatchObject({raw_gpus:8,initial_gpus:256,storage:[]});
 expect(record.data.projection_snapshot.payload.requirements.target_gpu_count).toBe(256);
 await page.screenshot({path:output+'/03-saved-deliverables.png',fullPage:true});
 expect(errors).toEqual([]);
 writeFileSync(output+'/result.json',JSON.stringify(result,null,2));
 writeFileSync(output+'/requirements.txt',summary);
 writeFileSync(output+'/completion.json',JSON.stringify(record,null,2));
 writeFileSync(output+'/validation.json',JSON.stringify({passed:true,scenario:'Case A document assistant',interpretation:'Fixed source-linked proposal supplied through API. No live LLM qualification claimed.',gui:['review facts','accept assumptions','calculate','compare GPUs','export','prepare handoff','complete','reload','retrieve'],expected:{requests_per_minute:40,workload_gpus:8,factory_gpus:256,local_storage_tiers:0,initial_transfer:'not specified'},console_errors:errors},null,2));
});

